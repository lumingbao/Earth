use super::should_ignore_app;
use crate::model::{ActiveAppInfo, AppSettings};

pub(super) fn source_allowed(app: Option<&ActiveAppInfo>, settings: &AppSettings) -> bool {
    !settings.ignored_apps.iter().any(|s| !s.trim().is_empty())
        || app.is_some_and(|a| {
            (!a.app_name.is_empty() || !a.process_or_bundle.is_empty())
                && !should_ignore_app(&a.app_name, &a.process_or_bundle, settings)
        })
}
fn canonical(s: &str) -> String {
    let name = s.trim().to_ascii_lowercase();
    match name.as_str() {
        "public.utf8-plain-text"
        | "public.utf16-plain-text"
        | "public.plain-text"
        | "text/plain"
        | "cf_unicodetext"
        | "cf_text" => "text",
        "public.html" | "text/html" | "html format" => "html",
        "public.rtf" | "text/rtf" | "application/rtf" | "rich text format" => "rtf",
        "png" | "image/png" | "public.png" | "public.tiff" | "image/tiff" | "cf_dib"
        | "cf_dibv5" | "cf_bitmap" => "image",
        "cf_hdrop" | "public.file-url" | "text/uri-list" => "files",
        "concealedtype" => "org.nspasteboard.concealedtype",
        "transienttype" => "org.nspasteboard.transienttype",
        "autogeneratedtype" => "org.nspasteboard.autogeneratedtype",
        _ => return name,
    }
    .to_string()
}
pub(super) struct FormatRules(Vec<String>);
impl FormatRules {
    pub fn new(rules: &[String]) -> Self {
        Self(
            rules
                .iter()
                .map(|r| canonical(r))
                .filter(|r| !r.is_empty())
                .collect(),
        )
    }
    pub fn allows(&self, kind: &str) -> bool {
        !self.0.iter().any(|r| r == kind)
    }
    pub fn permits_event(
        &self,
        formats: Option<&[String]>,
        flag: impl Fn(&str) -> Option<u32>,
    ) -> bool {
        if self.0.is_empty() {
            return true;
        }
        let Some(formats) = formats.filter(|f| !f.is_empty()) else {
            return false;
        };
        for fmt in formats {
            let name = canonical(fmt);
            if self.allows(&name)
                || matches!(name.as_str(), "html" | "rtf" | "text" | "image" | "files")
            {
                continue;
            }
            if name == "canincludeinclipboardhistory" && flag(fmt) == Some(1) {
                continue;
            }
            return false;
        }
        true
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn history_dword_allow_flag_and_unknown_values_fail_closed() {
        let name = "CanIncludeInClipboardHistory".to_string();
        let rules = FormatRules::new(std::slice::from_ref(&name));
        let formats = [name];
        assert!(rules.permits_event(Some(&formats), |_| Some(1)));
        for value in [None, Some(0), Some(2)] {
            assert!(!rules.permits_event(Some(&formats), |_| value));
        }
        assert!(!rules.permits_event(None, |_| Some(1)));
    }

    #[test]
    fn representation_aliases_do_not_drop_unrelated_text() {
        let rules = FormatRules::new(&["html".into(), "CF_DIB".into()]);
        assert!(!rules.allows("html"));
        assert!(!rules.allows("image"));
        assert!(rules.allows("text"));
        assert!(rules.permits_event(
            Some(&["public.html".into(), "public.utf8-plain-text".into()]),
            |_| None
        ));
        let exact = FormatRules::new(&["secret".into()]);
        assert!(exact.permits_event(Some(&["com.app.secret-note".into()]), |_| None));
    }

    #[test]
    fn unknown_source_with_application_rules_is_rejected() {
        let settings = AppSettings {
            ignored_apps: vec!["Password".into()],
            ..Default::default()
        };
        assert!(!source_allowed(None, &settings));
        assert!(!source_allowed(Some(&ActiveAppInfo::default()), &settings));
    }
}
